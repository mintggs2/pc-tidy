/// <summary>Everything this test project writes lives under testbed\photos\.</summary>
internal static class Area
{
    public static readonly string Root = Path.Combine(FindCodeRoot(), "testbed", "photos");

    public static string NewFolder(string name) => Path.Combine(Root, $"{name}-{Guid.NewGuid().ToString("N")[..6]}");

    private static string FindCodeRoot()
    {
        var d = new DirectoryInfo(AppContext.BaseDirectory);
        while (d != null && !File.Exists(Path.Combine(d.FullName, "PcTidy.sln"))) d = d.Parent;
        return d?.FullName ?? throw new InvalidOperationException("PcTidy.sln not found above " + AppContext.BaseDirectory);
    }
}

/// <summary>A PC Tidy host (real SafetyGuard, Executor, Undo) over a sandbox tree: generated by TestbedGen, or hand-made.</summary>
public sealed class TestPc : IDisposable
{
    public static readonly ExecuteOptions Real = new() { Mode = ExecutionMode.Real, ContinueWithoutRestorePoint = _ => Task.FromResult(true) };

    private TestPc(string root, PcTidyHost host, TestbedInfo? info)
    {
        Root = root;
        Host = host;
        Info = info;
    }

    /// <summary>A generated fake PC (few bulk files, so it's quick).</summary>
    public static TestPc Generated(string name, SandboxProfile profile)
    {
        var root = Area.NewFolder(name);
        var info = TestbedBuilder.Generate(root, TestbedSize.Small, profile, new TestbedOptions { BulkFiles = 50 });
        return new TestPc(root, PcTidyHost.CreateSandbox(root, profile), info);
    }

    /// <summary>An empty fake PC with just the user folders.</summary>
    public static TestPc HandMade(string name, SandboxProfile? profile = null)
    {
        var root = Area.NewFolder(name);
        var p = profile ?? SandboxProfile.Minimal;
        var k = new SandboxKnownLocations(root, p);
        foreach (var d in new[] { k.Desktop, k.Documents, k.Downloads, k.Pictures, k.Videos, k.Music, k.LocalAppData, k.RoamingAppData, k.ProgramFiles, k.WindowsDir })
            Directory.CreateDirectory(d);
        foreach (var c in k.CloudRoots) Directory.CreateDirectory(c);
        return new TestPc(root, PcTidyHost.CreateSandbox(root, p), null);
    }

    public string Root { get; }
    public PcTidyHost Host { get; }
    public TestbedInfo? Info { get; }
    public IKnownLocations K => Host.Locations;

    public ScanContext Context(ScanDepth depth = ScanDepth.Quick, IReadOnlyList<string>? roots = null) => Host.CreateScanContext(depth, roots);

    public Photos.PhotoPlanner PhotoPlanner() => new(Host.Safety, Host.InUse, Host.Walker, Host.Settings);
    public Desktop.DesktopTidyPlanner DesktopPlanner() => new(Host.Safety, Host.InUse, Host.Walker, Host.Settings);

    /// <summary>Writes a file with an age (modified and created set to <paramref name="daysOld"/> days ago).</summary>
    public static string Put(string path, byte[] bytes, double daysOld = 40, FileAttributes attributes = 0)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllBytes(path, bytes);
        var t = DateTime.UtcNow.AddDays(-daysOld);
        File.SetLastWriteTimeUtc(path, t);
        File.SetCreationTimeUtc(path, t);
        if (attributes != 0) File.SetAttributes(path, File.GetAttributes(path) | attributes);
        return path;
    }

    public static string Put(string path, string text, double daysOld = 40, FileAttributes attributes = 0)
        => Put(path, System.Text.Encoding.UTF8.GetBytes(text), daysOld, attributes);

    /// <summary>Differences vs. a manifest, ignoring PC Tidy's own data folder (journal, quarantine).</summary>
    public ManifestDiff DiffFrom(TestbedManifest before)
    {
        var diff = TestbedBuilder.Compare(before, TestbedBuilder.Manifest(Root));
        return new ManifestDiff(diff.Differences.Where(d => !IsPcTidyOwn(d.Path)).ToList());
    }

    private static bool IsPcTidyOwn(string relative)
        => relative.StartsWith("Data\\", StringComparison.OrdinalIgnoreCase) || relative.Equals("Data", StringComparison.OrdinalIgnoreCase)
           || relative.Contains("PC Tidy Quarantine", StringComparison.OrdinalIgnoreCase);

    public static bool Same(string a, string b) => string.Equals(PathUtil.Normalize(a), PathUtil.Normalize(b), StringComparison.OrdinalIgnoreCase);

    public void Dispose()
    {
        Host.Dispose();
        try
        {
            if (Info is not null) TestbedBuilder.Delete(Root);
            else Directory.Delete(Root, recursive: true);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or InvalidOperationException) { /* disposable sandbox */ }
    }
}

/// <summary>
/// Synthetic photos made with WPF imaging on a private STA thread: a busy deterministic scene (many sharp-edged
/// blocks and lines, like the detail in a real photo), optionally shifted, blurred, and stamped with EXIF date taken.
/// </summary>
internal static class SyntheticPhotos
{
    public static byte[] Jpeg(int seed, DateTime? taken = null, int blur = 0, int shiftX = 0, int width = 320, int height = 240, int quality = 92)
        => RunSta(() =>
        {
            var gray = Scene(seed, width, height, shiftX);
            if (blur > 0) gray = BoxBlur(gray, width, height, blur);
            var bgr = new byte[width * height * 3];
            for (int i = 0; i < gray.Length; i++) { bgr[i * 3] = gray[i]; bgr[i * 3 + 1] = (byte)(gray[i] * 0.9); bgr[i * 3 + 2] = (byte)Math.Min(255, gray[i] + 10); }
            var bmp = BitmapSource.Create(width, height, 96, 96, PixelFormats.Bgr24, null, bgr, width * 3);
            BitmapMetadata? meta = null;
            if (taken is { } t)
            {
                meta = new BitmapMetadata("jpg");
                meta.SetQuery("/app1/ifd/exif/{ushort=36867}", t.ToString("yyyy:MM:dd HH:mm:ss", System.Globalization.CultureInfo.InvariantCulture));
            }
            var enc = new JpegBitmapEncoder { QualityLevel = quality };
            enc.Frames.Add(BitmapFrame.Create(bmp, null, meta, null));
            using var ms = new MemoryStream();
            enc.Save(ms);
            return ms.ToArray();
        });

    private static byte[] Scene(int seed, int w, int h, int shiftX)
    {
        var rng = new Random(seed);
        var px = new byte[w * h];
        for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++)
                px[y * w + x] = (byte)(60 + 80.0 * y / h);
        for (int k = 0; k < 60; k++)
        {
            int bx = rng.Next(-20, w) + shiftX, by = rng.Next(-20, h), bw = rng.Next(6, 50), bh = rng.Next(6, 40);
            byte c = (byte)rng.Next(0, 256);
            for (int y = Math.Max(0, by); y < Math.Min(h, by + bh); y++)
                for (int x = Math.Max(0, bx); x < Math.Min(w, bx + bw); x++)
                    px[y * w + x] = c;
        }
        return px;
    }

    private static byte[] BoxBlur(byte[] src, int w, int h, int radius)
    {
        var dst = new byte[src.Length];
        for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++)
            {
                int sum = 0, n = 0;
                for (int dy = -radius; dy <= radius; dy++)
                    for (int dx = -radius; dx <= radius; dx++)
                    {
                        int xx = Math.Clamp(x + dx, 0, w - 1), yy = Math.Clamp(y + dy, 0, h - 1);
                        sum += src[yy * w + xx]; n++;
                    }
                dst[y * w + x] = (byte)(sum / n);
            }
        return dst;
    }

    public static T RunSta<T>(Func<T> work)
    {
        T result = default!;
        Exception? error = null;
        var thread = new Thread(() =>
        {
            try { result = work(); }
            catch (Exception ex) { error = ex; }
        });
        thread.SetApartmentState(ApartmentState.STA);
        thread.Start();
        thread.Join();
        if (error is not null) throw new InvalidOperationException("Image work failed", error);
        return result;
    }
}
