namespace PcTidy.Features.Privacy.Tests;

/// <summary>Everything this test project writes on disk lives under testbed\privacy\.</summary>
internal static class Area
{
    public static readonly string Root = Path.Combine(FindCodeRoot(), "testbed", "privacy");

    public static string NewFolder(string name) => Path.Combine(Root, $"{name}-{Guid.NewGuid().ToString("N")[..6]}");

    private static string FindCodeRoot()
    {
        var d = new DirectoryInfo(AppContext.BaseDirectory);
        while (d != null && !File.Exists(Path.Combine(d.FullName, "PcTidy.sln"))) d = d.Parent;
        return d?.FullName ?? throw new InvalidOperationException("PcTidy.sln not found above " + AppContext.BaseDirectory);
    }
}

/// <summary>
/// A throw-away registry area under HKCU\Software\PCTidyTest\privacy\&lt;random&gt; (the only place these tests write),
/// deleted on dispose. <see cref="Registry"/> reads it as if it were HKCU.
/// </summary>
public sealed class TestRegistry : IDisposable
{
    public TestRegistry()
    {
        Root = $@"Software\PCTidyTest\privacy\{Guid.NewGuid():N}";
        using (var k = Microsoft.Win32.Registry.CurrentUser.CreateSubKey(Root)) { }
        Registry = UserRegistry.Redirected(Root);
    }

    public string Root { get; }
    public UserRegistry Registry { get; }

    /// <summary>The physical key for a logical HKCU key.</summary>
    public string Key(string logical) => Registry.Map(logical);

    public void SetDword(string logicalKey, string name, int value)
    {
        using var k = Microsoft.Win32.Registry.CurrentUser.CreateSubKey(Key(logicalKey));
        k.SetValue(name, value, RegistryValueKind.DWord);
    }

    public void SetString(string logicalKey, string name, string value)
    {
        using var k = Microsoft.Win32.Registry.CurrentUser.CreateSubKey(Key(logicalKey));
        k.SetValue(name, value, RegistryValueKind.String);
    }

    public void CreateKey(string logicalKey)
    {
        using var k = Microsoft.Win32.Registry.CurrentUser.CreateSubKey(Key(logicalKey));
    }

    /// <summary>Every key and value under the root, as sorted lines ("key|name|kind|data"), for before/after comparisons.</summary>
    public IReadOnlyList<string> Snapshot()
    {
        var lines = new List<string>();
        void Walk(string path)
        {
            using var k = Microsoft.Win32.Registry.CurrentUser.OpenSubKey(path);
            if (k is null) return;
            var rel = path.Length > Root.Length ? path[(Root.Length + 1)..] : "";
            lines.Add(rel + "|");
            foreach (var n in k.GetValueNames())
                lines.Add($"{rel}|{n}|{k.GetValueKind(n)}|{k.GetValue(n)}");
            foreach (var s in k.GetSubKeyNames()) Walk(path + "\\" + s);
        }
        Walk(Root);
        return lines.OrderBy(l => l, StringComparer.OrdinalIgnoreCase).ToList();
    }

    public NotificationsEnvironment Environment(AiFeatureFacts? ai = null) => new(Registry, new FixedAiFeatureProbe(ai ?? AiFeatureFacts.None));

    public void Dispose()
    {
        try
        {
            Microsoft.Win32.Registry.CurrentUser.DeleteSubKeyTree(Root, throwOnMissingSubKey: false);
            // The area key itself goes too once no other test is using it (Rule 3: delete the key afterwards).
            const string area = @"Software\PCTidyTest\privacy";
            bool empty;
            using (var k = Microsoft.Win32.Registry.CurrentUser.OpenSubKey(area)) empty = k is not null && k.SubKeyCount == 0 && k.ValueCount == 0;
            if (empty) Microsoft.Win32.Registry.CurrentUser.DeleteSubKey(area, throwOnMissingSubKey: false);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or System.Security.SecurityException or InvalidOperationException) { /* test area only */ }
    }
}

/// <summary>A PC Tidy host (real SafetyGuard, Executor, Undo) over a sandbox tree: generated by TestbedGen, or hand-made.</summary>
public sealed class TestPc : IDisposable
{
    public static readonly ExecuteOptions Real = new() { Mode = ExecutionMode.Real, ContinueWithoutRestorePoint = _ => Task.FromResult(true) };

    private TestPc(string root, PcTidyHost host, TestbedInfo? info)
    {
        Root = root;
        Host = host;
        Info = info;
    }

    /// <summary>A generated fake PC (few bulk files, so it's quick).</summary>
    public static TestPc Generated(string name, SandboxProfile profile)
    {
        var root = Area.NewFolder(name);
        var info = TestbedBuilder.Generate(root, TestbedSize.Small, profile, new TestbedOptions { BulkFiles = 50 });
        return new TestPc(root, PcTidyHost.CreateSandbox(root, profile), info);
    }

    /// <summary>An empty fake PC with just the user folders.</summary>
    public static TestPc HandMade(string name, SandboxProfile? profile = null)
    {
        var root = Area.NewFolder(name);
        var p = profile ?? SandboxProfile.Minimal;
        var k = new SandboxKnownLocations(root, p);
        foreach (var d in new[] { k.Desktop, k.Documents, k.Downloads, k.Pictures, k.Videos, k.Music, k.LocalAppData, k.RoamingAppData, k.ProgramFiles, k.WindowsDir })
            Directory.CreateDirectory(d);
        foreach (var c in k.CloudRoots) Directory.CreateDirectory(c);
        return new TestPc(root, PcTidyHost.CreateSandbox(root, p), null);
    }

    public string Root { get; }
    public PcTidyHost Host { get; }
    public TestbedInfo? Info { get; }
    public IKnownLocations K => Host.Locations;

    public ScanContext Context(string? preset = null) => Host.CreateScanContext(ScanDepth.Quick, null, preset);

    /// <summary>Writes a small file with an age.</summary>
    public static string Put(string path, string text = "x", double daysOld = 3)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text);
        var t = DateTime.UtcNow.AddDays(-daysOld);
        File.SetLastWriteTimeUtc(path, t);
        File.SetCreationTimeUtc(path, t);
        return path;
    }

    /// <summary>Differences vs. a manifest, ignoring PC Tidy's own data folder (journal, quarantine).</summary>
    public ManifestDiff DiffFrom(TestbedManifest before)
    {
        var diff = TestbedBuilder.Compare(before, TestbedBuilder.Manifest(Root));
        return new ManifestDiff(diff.Differences.Where(d => !IsPcTidyOwn(d.Path)).ToList());
    }

    private static bool IsPcTidyOwn(string relative)
        => relative.StartsWith("Data\\", StringComparison.OrdinalIgnoreCase) || relative.Equals("Data", StringComparison.OrdinalIgnoreCase)
           || relative.Contains("PC Tidy Quarantine", StringComparison.OrdinalIgnoreCase);

    public void Dispose()
    {
        Host.Dispose();
        try
        {
            if (Info is not null) TestbedBuilder.Delete(Root);
            else Directory.Delete(Root, recursive: true);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or InvalidOperationException) { /* disposable sandbox */ }
    }
}

internal static class Runs
{
    public static string Problems(RunRecord run)
        => string.Join("\n", run.Steps.Where(s => s.Status != StepStatus.Done).Select(s => $"{s.Status} {s.Item.Description}: {s.Message}"));
}
