        c.NeverTree(Path.Combine(win, "SoftwareDistribution", "DataStore"), "Windows Update database (only Download is a carve-out)");
    }

    private static void WindowsCarveOuts(Ctx c)
    {
        var win = c.K.WindowsDir;
        var temp = c.K.WindowsTemp;
        foreach (var (name, age) in new[] { ("MpCmdRun.log", 40.0), ("DISM-old.log", 90), ("~DF3A1B.tmp", 12), ("msi4f2a.LOG", 300) })
            c.Put(Path.Combine(temp, name), c.F.Blob(), age, "cleanup,windows-temp,old");
        c.Put(Path.Combine(temp, "{6F1A2B3C-0000-4D5E-8F90-ABCDEF123456}", "setup.dll"), c.F.Dll(), 25, "cleanup,windows-temp,old");
        c.EmptyDir(Path.Combine(temp, "OldEmptyDir"), 20, "cleanup,windows-temp,old,empty-folder");
        c.Put(Path.Combine(temp, "fresh-session.tmp"), c.F.Blob(), 0.1, "cleanup,windows-temp,fresh");
        c.Put(Path.Combine(temp, "in-use.tmp"), c.F.Blob(), 10, "cleanup,windows-temp,old,lock-candidate");

        var minidump = Path.Combine(win, "Minidump");
        c.Put(Path.Combine(minidump, "031525-12345-01.dmp"), c.F.Dump(), 240, "cleanup,crash-dump,old");
        c.Put(Path.Combine(minidump, "110825-23456-01.dmp"), c.F.Dump(), 2, "cleanup,crash-dump,fresh");
        // MEMORY.DMP: the single file carve-out, big (sparse) as in real life.
        c.Sparse(Path.Combine(win, "MEMORY.DMP"), c.F.Dump(4_096, 4_097), 1_200L * 1024 * 1024, 60, "cleanup,crash-dump,old,memory-dmp");
        c.Put(Path.Combine(win, "LiveKernelReports", "WATCHDOG", "WD-20250901-1012.dmp"), c.F.Dump(), 430, "cleanup,crash-dump,old");
        c.Put(Path.Combine(win, "LiveKernelReports", "USBXHCI-20261101-0901.dmp"), c.F.Dump(), 9, "cleanup,crash-dump,fresh");

        var cbs = Path.Combine(win, "Logs", "CBS");
        c.Canary(Path.Combine(cbs, "CBS.log"), c.F.Blob(40_000, 120_000), 0.05, "Live CBS.log: never cleaned");
        c.Put(Path.Combine(cbs, "CbsPersist_20250901101112.cab"), c.F.Cab(), 430, "cleanup,windows-logs,old");
        c.Put(Path.Combine(cbs, "CbsPersist_20251212080910.log"), c.F.Blob(30_000, 90_000), 330, "cleanup,windows-logs,old");
        c.Put(Path.Combine(cbs, "CbsPersist_20261105120000.cab"), c.F.Cab(), 5, "cleanup,windows-logs,fresh");
