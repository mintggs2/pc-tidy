        c.Put(Path.Combine(dism, "dism.log"), c.F.Blob(20_000, 80_000), 0.5, "cleanup,windows-logs,fresh");
        c.Put(Path.Combine(dism, "dism.2025-02-11.log"), c.F.Blob(20_000, 80_000), 270, "cleanup,windows-logs,old");

        var download = Path.Combine(win, "SoftwareDistribution", "Download");
        c.Put(Path.Combine(download, "0a1b2c3d4e5f60718293a4b5c6d7e8f9", "Windows11.0-KB5040001-x64.cab"), c.F.Cab(), 45, "cleanup,update-downloads,old");
        c.Put(Path.Combine(download, "f9e8d7c6b5a4938271605f4e3d2c1b0a", "Windows11.0-KB5046002-x64.cab"), c.F.Cab(), 2, "cleanup,update-downloads,fresh");
        c.Put(Path.Combine(download, "SharedFileCache", "3f2e1d.bin"), c.F.Blob(), 20, "cleanup,update-downloads,old");
    }

