        var sys32 = Path.Combine(win, "System32");
        foreach (var dll in new[] { "kernel32.dll", "ntdll.dll", "user32.dll", "shell32.dll" })
            c.Put(Path.Combine(sys32, dll), c.F.Dll(), 30, "protected");
        c.Put(Path.Combine(sys32, "drivers", "etc", "hosts"), Fake.Text("# hosts file\r\n127.0.0.1 localhost\r\n"), 400, "protected");
        c.Put(Path.Combine(sys32, "DriverStore", "FileRepository", "fakegpu.inf_amd64_1a2b3c4d5e6f7a8b", "fakegpu.inf"),
            Fake.Text("[Version]\r\nSignature=\"$WINDOWS NT$\"\r\n"), 120, "protected,driver");
        c.Put(Path.Combine(sys32, "DriverStore", "FileRepository", "fakegpu.inf_amd64_1a2b3c4d5e6f7a8b", "fakegpu.sys"), c.F.Dll(), 120, "protected,driver");
        c.NeverTree(sys32, "System32 incl. DriverStore");
        var sxs = Path.Combine(win, "WinSxS", "amd64_microsoft-windows-fake_31bf3856ad364e35_10.0.26100.1_none_0123456789abcdef");
        c.Put(Path.Combine(sxs, "fake.dll"), c.F.Dll(), 300, "protected,winsxs");
        c.NeverTree(Path.Combine(win, "WinSxS"), "Component store: DISM only");
        var installer = Path.Combine(win, "Installer");
        c.Put(Path.Combine(installer, "1a2b3c.msi"), c.F.Msi(), 500, "protected");
        c.Put(Path.Combine(installer, "{11111111-2222-3333-4444-555555555555}", "app.ico"), c.F.Blob(1_000, 5_000), 500, "protected");
        c.NeverTree(installer, "Windows Installer cache: needed to repair/uninstall apps");
        var prefetch = Path.Combine(win, "Prefetch");
        c.Put(Path.Combine(prefetch, "CHROME.EXE-1A2B3C4D.pf"), c.F.Blob(5_000, 40_000), 1, "protected");
        c.Put(Path.Combine(prefetch, "EXPLORER.EXE-ABCDEF01.pf"), c.F.Blob(5_000, 40_000), 0.5, "protected");
        c.NeverTree(prefetch, "Prefetch: deliberately not cleaned");
        c.Put(Path.Combine(win, "Fonts", "arial.ttf"), c.F.Blob(60_000, 200_000), 600, "protected");
        c.NeverTree(Path.Combine(win, "Fonts"), "Fonts");
