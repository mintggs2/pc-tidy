using PcTidy.TestbedGen.Content;

namespace PcTidy.TestbedGen.Layout;

/// <summary>C:\ root files, C:\Windows (protected tree + the exact carve-outs of Plan §7), Program Files, ProgramData.</summary>
internal static class SystemArea
{
    /// <summary>Folder name of the simulated user's Recycle Bin (a real one is named after the user's SID).</summary>
    public const string RecycleBinSid = "S-1-5-21-test";

    public static void Build(Ctx c)
    {
        DriveRoot(c);
        RecycleBin(c);
        SystemStateIni(c);
        WindowsProtected(c);
        WindowsCarveOuts(c);
        ProgramFiles(c);
        ProgramData(c);
    }

    /// <summary>
    /// Simulated registry/power facts read by Cleanup's SandboxSystemState (<c>key=value</c>, flags 0/1),
    /// kept consistent with Sim\sim.json: HasBattery = isLaptop, RebootPending = rebootPending.
    /// </summary>
    private static void SystemStateIni(Ctx c)
    {
        static string B(bool v) => v ? "1" : "0";
        long memory = (c.Hw.IsLaptop ? 16L : 32L) * 1024 * 1024 * 1024;
        var ini = "# Simulated Windows state for PC Tidy sandbox runs (generated by PcTidy.TestbedGen; matches Sim\\sim.json)\r\n" +
                  $"RebootPending={B(c.Hw.RebootPending)}\r\n" +
                  "HibernateEnabled=1\r\n" +
                  "HiberFileType=2\r\n" +                       // 2 = Full, 1 = Reduced
                  $"HasBattery={B(c.Hw.IsLaptop)}\r\n" +
                  $"TotalMemoryBytes={memory}\r\n" +
                  "PagingFiles=?:\\pagefile.sys\r\n" +          // "?:" = size managed by Windows on every drive
                  "ReservedStorage=1\r\n" +
                  "CompactOS=0\r\n";
        var path = Path.Combine(c.K.WindowsDir, "PcTidy.Sandbox", "system-state.ini");
        c.Put(path, Fake.Text(ini), 0, "sim,system-state");
        c.Never(path, "Simulated system state (inside Windows: never touched)");
    }

    /// <summary>The sandbox Recycle Bin: Windows' $I (metadata) / $R (content) pairs, plus a deleted folder.
    /// Emptying it is Permanent and never default-ticked, so it survives every default run.</summary>
    private static void RecycleBin(Ctx c)
    {
        const FileAttributes hs = FileAttributes.Hidden | FileAttributes.System;
        var bin = Path.Combine(c.DriveC, "$Recycle.Bin");
        var sid = Path.Combine(bin, RecycleBinSid);
        c.Put(Path.Combine(sid, "desktop.ini"), Fake.Text("[.ShellClassInfo]\r\nCLSID={645FF040-5081-101B-9F08-00AA002F954E}\r\n"), 300, "recycle-bin", hs);
        (string Id, string Original, byte[] Data, double Age)[] items =
        {
            ("A1B2C3.txt", Path.Combine(c.K.Documents, "old draft.txt"), c.F.Lines("Old draft"), 12),
            ("D4E5F6.jpg", Path.Combine(c.K.Pictures, "blurry.jpg"), c.Photo(c.Seed + 500), 40),
            ("G7H8I9.zip", Path.Combine(c.K.Downloads, "unused-tool.zip"), Formats.Zip(("tool.exe", c.F.Exe(2_000, 4_000))), 3),
        };
        foreach (var (id, original, data, age) in items)
        {
            c.Put(Path.Combine(sid, "$R" + id), data, age, "recycle-bin");
            c.Put(Path.Combine(sid, "$I" + id), RecycleInfo(original, data.Length, c.Ago(age)), age, "recycle-bin");
        }
        var folder = Path.Combine(sid, "$RJ0K1L2");
        c.Put(Path.Combine(folder, "notes.txt"), c.F.Lines("Deleted folder"), 25, "recycle-bin");
        c.Put(Path.Combine(folder, "photo.png"), c.Png(c.Seed + 501, 40, 30), 25, "recycle-bin");
        c.Put(Path.Combine(sid, "$IJ0K1L2"), RecycleInfo(Path.Combine(c.K.Desktop, "Old project"), 0, c.Ago(25)), 25, "recycle-bin");
        c.W.SetAttributes(bin, hs);
        c.DefaultTree(bin, "Recycle Bin: emptying is Permanent, never default-ticked");
    }

    /// <summary>$I file, version 2 (Windows 10+): header, original size, deletion FILETIME, path length, UTF-16 path.</summary>
    private static byte[] RecycleInfo(string originalPath, long size, DateTime deletedUtc)
    {
        using var ms = new MemoryStream();
        using var w = new BinaryWriter(ms);
        w.Write(2L);
        w.Write(size);
        w.Write(deletedUtc.ToFileTimeUtc());
        w.Write(originalPath.Length + 1);
        w.Write(System.Text.Encoding.Unicode.GetBytes(originalPath + "\0"));
        w.Flush();
        return ms.ToArray();
    }

    private static void DriveRoot(Ctx c)
    {
        const FileAttributes hs = FileAttributes.Hidden | FileAttributes.System;
        foreach (var name in new[] { "pagefile.sys", "hiberfil.sys", "swapfile.sys" })
        {
            c.Put(Path.Combine(c.DriveC, name), c.F.Blob(64_000, 128_000), 0.2, "protected,system-file", hs);
            c.Never(Path.Combine(c.DriveC, name), "Windows page/hibernate file");
        }
        var svi = Path.Combine(c.DriveC, "System Volume Information");
        c.Put(Path.Combine(svi, "tracking.log"), c.F.Blob(), 3, "protected", hs);
        c.W.SetAttributes(svi, hs);
        c.NeverTree(svi, "System Volume Information");
        var recovery = Path.Combine(c.DriveC, "Recovery");
        c.Put(Path.Combine(recovery, "ReAgentOld.xml"), Fake.Text("<WindowsRE version=\"2.0\"/>"), 200, "protected", hs);
        c.NeverTree(recovery, "Recovery partition files");
        var xbox = Path.Combine(c.DriveC, "XboxGames", "Fake Xbox Game", "Content");
        c.Put(Path.Combine(xbox, "game.exe"), c.F.Exe(), 90, "game");
        c.Put(Path.Combine(xbox, "data.pak"), c.F.Blob(50_000, 200_000), 90, "game");
        c.NeverTree(Path.Combine(c.DriveC, "XboxGames"), "Xbox / Game Pass install");
    }

    private static void WindowsProtected(Ctx c)
